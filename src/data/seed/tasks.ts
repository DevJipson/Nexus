import type {
  Attachment,
  Comment,
  ID,
  Priority,
  Subtask,
  Task,
  TaskLabel,
  TaskStatus,
} from "@/types/domain";
import { seedAt } from "@/data/seed/time";

interface TaskSeed {
  id: string;
  workspaceId: ID;
  projectId: ID;
  title: string;
  description: string;
  status: TaskStatus;
  priority: Priority;
  assigneeId: ID | null;
  reporterId?: ID;
  dueInDays?: number | null;
  dueHour?: number;
  labels?: TaskLabel[];
  order: number;
  createdDaysAgo?: number;
  completedDaysAgo?: number | null;
  subtasks?: Array<[title: string, done: boolean]>;
  comments?: Array<[authorId: ID, body: string, daysAgo: number]>;
  attachments?: Array<[name: string, size: number, mimeType: string, daysAgo: number]>;
}

function makeTask(seed: TaskSeed): Task {
  const subtasks: Subtask[] = (seed.subtasks ?? []).map(([title, done], index) => ({
    id: `${seed.id}-s${index + 1}`,
    title,
    done,
  }));

  const comments: Comment[] = (seed.comments ?? []).map(
    ([authorId, body, daysAgo], index) => ({
      id: `${seed.id}-c${index + 1}`,
      authorId,
      body,
      createdAt: seedAt(-daysAgo, 11 + index, 20),
    }),
  );

  const attachments: Attachment[] = (seed.attachments ?? []).map(
    ([name, size, mimeType, daysAgo], index) => ({
      id: `${seed.id}-a${index + 1}`,
      name,
      size,
      mimeType,
      uploadedAt: seedAt(-daysAgo, 15, 5 + index),
    }),
  );

  const createdAt = seedAt(-(seed.createdDaysAgo ?? 18), 10);
  const completedAt =
    seed.completedDaysAgo == null ? null : seedAt(-seed.completedDaysAgo, 16);

  const candidates = [
    createdAt,
    ...comments.map((comment) => comment.createdAt),
    ...attachments.map((attachment) => attachment.uploadedAt),
    completedAt ?? createdAt,
  ].sort();

  return {
    id: seed.id,
    workspaceId: seed.workspaceId,
    projectId: seed.projectId,
    title: seed.title,
    description: seed.description,
    status: seed.status,
    priority: seed.priority,
    assigneeId: seed.assigneeId,
    reporterId: seed.reporterId ?? "m-maya",
    dueDate:
      seed.dueInDays == null ? null : seedAt(seed.dueInDays, seed.dueHour ?? 17),
    labels: seed.labels ?? [],
    order: seed.order,
    subtasks,
    comments,
    attachments,
    createdAt,
    updatedAt: candidates[candidates.length - 1],
    completedAt,
  };
}

