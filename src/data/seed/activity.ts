import type { ActivityEntry } from "@/types/domain";
import { seedAt } from "@/data/seed/time";

interface ActivitySeed {
  id: string;
  workspaceId: string;
  actorId: string;
  kind: ActivityEntry["kind"];
  entityType: ActivityEntry["entityType"];
  entityId: string;
  entityLabel: string;
  projectId?: string | null;
  daysAgo: number;
  hour: number;
  minute: number;
}

function entry(seed: ActivitySeed): ActivityEntry {
  return {
    id: seed.id,
    workspaceId: seed.workspaceId,
    actorId: seed.actorId,
    kind: seed.kind,
    entityType: seed.entityType,
    entityId: seed.entityId,
    entityLabel: seed.entityLabel,
    projectId: seed.projectId ?? null,
    createdAt: seedAt(-seed.daysAgo, seed.hour, seed.minute),
  };
}

