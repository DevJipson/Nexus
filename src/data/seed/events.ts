import type { CalendarEvent } from "@/types/domain";
import { seedAt } from "@/data/seed/time";

interface EventSeed {
  id: string;
  workspaceId: string;
  title: string;
  description: string;
  type: CalendarEvent["type"];
  projectId?: string | null;
  day: number;
  startHour?: number;
  startMinute?: number;
  durationMinutes?: number;
  allDay?: boolean;
  attendeeIds: string[];
  location?: string;
}

function makeEvent(seed: EventSeed): CalendarEvent {
  const startHour = seed.startHour ?? 9;
  const startMinute = seed.startMinute ?? 0;
  const duration = seed.durationMinutes ?? 60;
  const start = seedAt(seed.day, startHour, startMinute);
  const end = seed.allDay
    ? seedAt(seed.day, 23, 59)
    : new Date(new Date(start).getTime() + duration * 60_000).toISOString();

  return {
    id: seed.id,
    workspaceId: seed.workspaceId,
    title: seed.title,
    description: seed.description,
    type: seed.type,
    projectId: seed.projectId ?? null,
    start,
    end,
    allDay: seed.allDay ?? false,
    attendeeIds: seed.attendeeIds,
    location: seed.location ?? "",
    createdAt: seedAt(seed.day - 14, 10),
  };
}

